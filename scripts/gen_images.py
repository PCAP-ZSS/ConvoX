#!/usr/bin/env python3
"""Generate the synthetic benchmark images into data/images/ and write images.csv.

Convolution time does not depend on pixel content, so procedural images give exact
resolutions with no licensing questions. Each image mixes smooth regions and sharp
edges so blur and Sobel outputs are easy to judge by eye.
"""
import csv
import pathlib

import matplotlib.image as mpimg
import numpy as np

OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "images"

SPECS = [
    # image_id, width, height, class, pattern, seed
    ("img01_4k", 3840, 2160, "4k", "blobs", 1),
    ("img02_4k", 3840, 2160, "4k", "shapes", 2),
    ("img03_8k", 7680, 4320, "8k", "blobs", 3),
    ("img04_8k", 7680, 4320, "8k", "shapes", 4),
]


def blobs(w, h, rng):
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    img = 0.5 + 0.25 * np.sin(x / (w / 9.0)) * np.cos(y / (h / 7.0))
    for _ in range(40):
        cx, cy = rng.uniform(0, w), rng.uniform(0, h)
        r = rng.uniform(0.02, 0.08) * w
        img += rng.uniform(-0.4, 0.4) * np.exp(-((x - cx) ** 2 + (y - cy) ** 2) / (2 * r * r))
    img += rng.normal(0, 0.03, (h, w)).astype(np.float32)
    return img


def shapes(w, h, rng):
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    cell = max(w // 48, 8)
    img = (((x // cell) + (y // cell)) % 2).astype(np.float32) * 0.5 + 0.2
    for _ in range(25):
        cx, cy = rng.uniform(0, w), rng.uniform(0, h)
        r = rng.uniform(0.02, 0.1) * w
        img[(x - cx) ** 2 + (y - cy) ** 2 < r * r] = rng.uniform(0, 1)
    for _ in range(20):
        x0 = int(rng.uniform(0, w))
        img[:, x0 : x0 + 3] = rng.uniform(0, 1)
    img += rng.normal(0, 0.02, (h, w)).astype(np.float32)
    return img


PATTERNS = {"blobs": blobs, "shapes": shapes}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for image_id, w, h, cls, pattern, seed in SPECS:
        rng = np.random.default_rng(seed)
        img = np.clip(PATTERNS[pattern](w, h, rng), 0, 1)
        path = OUT / f"{image_id}.png"
        mpimg.imsave(path, img, cmap="gray", vmin=0, vmax=1)
        rows.append([image_id, f"{image_id}.png", w, h, cls,
                     f"synthetic ({pattern}, seed {seed}), generated by scripts/gen_images.py"])
        print(f"wrote {path.name} {w}x{h}")
    with open(OUT / "images.csv", "w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(["image_id", "path", "width", "height", "class", "source"])
        wr.writerows(rows)


if __name__ == "__main__":
    main()
